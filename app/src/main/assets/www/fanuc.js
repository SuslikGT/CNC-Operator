function grindCorrMount(){
  const mseg = $('gc_mode');
  if(mseg) mseg.addEventListener('seg', () => {
    GR_UNIT = segVal('gc_mode') || 'dia';
    grindCorrCalc();
  });
  ['gc_nom','gc_meas','gc_dress','gc_xm','gc_xd'].forEach(id => {
    const el = $(id); if(el){ el.addEventListener('input', grindCorrCalc); el.addEventListener('change', grindCorrCalc); }
  });
  grindCorrCalc();
}

function grindCorrCalc(){
  const nom = num('gc_nom', 0), meas = num('gc_meas', 0);
  const o1 = $('gc_out1');
  if(o1){
    if(nom > 0 && isFinite(meas)){
      const diff = meas - nom;
      const k = GR_UNIT === 'dia' ? 2 : 1;
      const corr = -diff / k;
      o1.innerHTML = rbox('Отклонение по Ø', (diff > 0 ? '+' : '') + fmt(diff, 3), 'мм', diff > 0 ? 'bad' : 'good') +
        rbox('Ввести в износ X', (corr > 0 ? '+' : '') + fmt(corr, 3), 'мм', 'lead') +
        '<div class="note" style="grid-column:1/-1">' +
        (Math.abs(diff) < 0.002 ? 'В пределах 2 мкм — не трогаем.' :
          (diff > 0 ? 'Диаметр больше: в износ X <b>вычесть</b> ' + fmt(Math.abs(corr), 3) + ' мм.'
                    : 'Диаметр меньше: в износ X <b>прибавить</b> ' + fmt(Math.abs(corr), 3) + ' мм.')) +
        ' X сейчас считается ' + (GR_UNIT === 'dia' ? 'в диаметрах' : 'в радиусах') + '.</div>';
    } else o1.innerHTML = '';
  }

  const dress = num('gc_dress', 0);
  const o2 = $('gc_out2');
  if(o2){
    o2.innerHTML = rbox('Компенсация после правки', '+ ' + fmt(GR_UNIT === 'dia' ? dress * 2 : dress, 3), 'мм', 'lead') +
      '<div class="note" style="grid-column:1/-1">Круг стал меньше на ' + fmt(dress, 3) +
      ' мм по радиусу — столько и компенсируем по X (в диаметрах — удвоенное). ' +
      'Правку глубже 0,03 мм за проход не делайте: крошится кромка.</div>';
  }

  const xm = num('gc_xm', 0), xd = num('gc_xd', 0);
  const ox = $('gc_outx');
  if(ox){
    if(xm !== 0 && xd > 0){
      const g54 = GR_UNIT === 'dia' ? xm - xd : xm - xd / 2;
      ox.innerHTML = rbox('Нуль G54 по X', fmt(g54, 3), 'мм', 'lead') +
        '<div class="note" style="grid-column:1/-1">Машинная координата касания эталона минус его размер ' +
        '(в диаметрах — весь Ø, в радиусах — половина). Затем проверьте первую деталь.</div>';
    } else ox.innerHTML = '';
  }
}

